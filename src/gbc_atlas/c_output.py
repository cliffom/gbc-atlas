"""GBDK-compatible arrays and the version 1 C type contract."""

from importlib.resources import files

from ._validation import require, validate_bank
from .model import Atlas


def render_types() -> str:
    """Return the shared C header bundled with this release."""
    return files("gbc_atlas").joinpath("asset_types.h").read_text(encoding="utf-8")


def render_c(
    data: Atlas, *, generator_label: str = "gbc-atlas", bank: str | int | None = None
) -> dict[str, str]:
    """Return deterministic C and header text without writing files.

    generator_label permits consumers to preserve existing provenance comments.
    bank opts into GBDK output; one bank reference covers every array in this file.
    A deduplicated Atlas emits cell_flags as an optional interface v1 extension.
    """
    require(
        "\n" not in generator_label
        and "\r" not in generator_label
        and "*/" not in generator_label,
        "Invalid generator label",
    )
    validate_bank(bank)
    m, digest = data.manifest, data.digest
    tiles, cell_tiles, palettes, regions = (
        data.tiles,
        data.cell_tiles,
        data.palettes,
        data.regions,
    )
    cols, rows = data.dimensions
    name = m["id"]
    upper = name.upper()
    header = [
        f"/* Generated by {generator_label}; approval {digest}. */",
        f"#ifndef ASSET_{upper}_H",
        f"#define ASSET_{upper}_H",
        '#include "asset_types.h"',
    ]
    header.extend(
        [
            f"#define {upper}_COLUMNS {cols}",
            f"#define {upper}_ROWS {rows}",
            f"#define {upper}_TILE_COUNT {len(tiles) // 16}",
            f"#define {upper}_PALETTE_COUNT {len(m['palettes'])}",
        ]
    )
    source = [
        f"/* Generated by {generator_label}; approval {digest}. */",
        f'#include "{name}.h"',
    ]
    if bank is not None:
        source.insert(0, f"#pragma bank {255 if bank == 'auto' else bank}")
        source.append(f"BANKREF({name})")
        header.extend(
            [
                "#include <gbdk/platform.h>",
                f"#define {upper}_BANKED 1",
                f"BANKREF_EXTERN({name})",
            ]
        )

    def array(ctype, suffix, values):
        symbol = f"{name}_{suffix}"
        header.append(f"extern const {ctype} {symbol}[{len(values)}];")
        source.append(f"const {ctype} {symbol}[{len(values)}] = {{")
        source.extend(
            "    " + ", ".join(str(v) for v in values[i : i + 16]) + ","
            for i in range(0, len(values), 16)
        )
        source.append("};")

    array("uint8_t", "tiles", tiles)
    array("uint8_t", "cell_tiles", cell_tiles)
    array("uint8_t", "cell_palettes", m["cell_palettes"])
    if data.cell_flags is not None:
        header.extend(
            [
                f"#define {upper}_HAS_CELL_FLAGS 1",
                f"#define {upper}_CELL_FLIP_X 0x20",
                f"#define {upper}_CELL_FLIP_Y 0x40",
            ]
        )
        array("uint8_t", "cell_flags", data.cell_flags)
    array("uint16_t", "palettes", palettes)
    header.append(f"extern const AssetRegion {name}_regions[{len(regions)}];")
    source.append(f"const AssetRegion {name}_regions[{len(regions)}] = {{")
    source.extend("    {" + ", ".join(map(str, r)) + "}," for r in regions)
    source.append("};")
    for i, region in enumerate(m["regions"]):
        header.append(f"#define {upper}_REGION_{region['name'].upper()} {i}")
    for a in m.get("animations", []):
        names = [r["name"] for r in m["regions"]]
        header.append(
            f"#define {upper}_ANIM_{a['name'].upper()}_COUNT {len(a['frames'])}"
        )
        array(
            "uint8_t",
            a["name"] + "_regions",
            [names.index(f["region"]) for f in a["frames"]],
        )
        array(
            "uint16_t",
            a["name"] + "_duration_ms",
            [
                f.get(
                    "duration_ms",
                    m["regions"][names.index(f["region"])].get("duration_ms"),
                )
                for f in a["frames"]
            ],
        )
    header.append("#endif")
    return {
        f"{name}.h": "\n".join(header) + "\n",
        f"{name}.c": "\n".join(source) + "\n",
    }
